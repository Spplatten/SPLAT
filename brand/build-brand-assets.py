"""Derive every shipped SPLAT brand asset from the two source renders in this folder.

    py -3 brand/build-brand-assets.py

The renders arrive as JPEG on a dark studio backdrop - image 2 carries a top-centre vignette that
runs from luma 13 to 72 - so no single threshold separates mark from backdrop. The backdrop is
modelled instead: a biquadratic surface fitted robustly to the pixels it already explains, with
alpha taken from each pixel's distance to that surface. Interior detail survives because the dark
regions the model matches are then classified rather than blanket-keyed - connected to the frame is
backdrop, enclosed and wide is a letter counter, enclosed and thin is a facet seam the artwork drew
on purpose.

Everything under src/MissionController.UI/Assets is generated by this script and should never be
hand-edited: the JPEGs beside it are the only originals, and the app, the taskbar icon and the MSIX
tiles all come off the same pass so they cannot drift apart.
"""
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter

BRAND = Path(__file__).resolve().parent
ASSETS = BRAND.parent / "src" / "MissionController.UI" / "Assets"

GRID_W, GRID_H = 48, 28      # resolution the fitted surface is rasterised at before bicubic upscale
T0, T1 = 7.0, 26.0           # distance-from-backdrop ramp: noise floor -> fully opaque
COUNTER_RADIUS = 4           # an enclosed dark region wider than this is a letter counter, not a seam
ICON_SIZES = [16, 20, 24, 32, 40, 48, 64, 128, 256]


# ------------------------------------------------------------------------------------------------
# Backdrop model: biquadratic (1, x, y, x^2, xy, y^2, x^2y, xy^2, x^2y^2) by normal equations.
# ------------------------------------------------------------------------------------------------
def basis(x, y):
    x2, y2 = x * x, y * y
    return (1.0, x, y, x2, x * y, y2, x2 * y, x * y2, x2 * y2)


def solve(a, b):
    n = len(b)
    m = [list(row) + [b[i]] for i, row in enumerate(a)]
    for col in range(n):
        pivot = max(range(col, n), key=lambda r: abs(m[r][col]))
        if abs(m[pivot][col]) < 1e-9:
            return None
        m[col], m[pivot] = m[pivot], m[col]
        inv = 1.0 / m[col][col]
        for c in range(col, n + 1):
            m[col][c] *= inv
        for r in range(n):
            if r != col and m[r][col] != 0.0:
                f = m[r][col]
                for c in range(col, n + 1):
                    m[r][c] -= f * m[col][c]
    return [m[r][n] for r in range(n)]


def fit(samples, w, h):
    coeffs = []
    for ch in range(3):
        ata = [[0.0] * 9 for _ in range(9)]
        atb = [0.0] * 9
        for x, y, rgb in samples:
            f = basis(x / w, y / h)
            v = rgb[ch]
            for i in range(9):
                fi = f[i]
                atb[i] += fi * v
                row = ata[i]
                for j in range(9):
                    row[j] += fi * f[j]
        for i in range(9):                      # ridge term: keeps the 9x9 conditioned on flat art
            ata[i][i] += 1e-6
        c = solve(ata, atb)
        if c is None:
            raise RuntimeError("backdrop fit is singular")
        coeffs.append(c)
    return coeffs


def render(coeffs, w, h):
    """Rasterise the fitted surface coarsely, then let PIL upscale it smoothly."""
    small = Image.new("RGB", (GRID_W, GRID_H))
    put = small.load()
    for gy in range(GRID_H):
        y = (gy + 0.5) / GRID_H
        for gx in range(GRID_W):
            f = basis((gx + 0.5) / GRID_W, y)
            put[gx, gy] = tuple(
                max(0, min(255, int(round(sum(f[i] * coeffs[ch][i] for i in range(9))))))
                for ch in range(3))
    return small.resize((w, h), Image.BICUBIC)


def backdrop_model(img):
    w, h = img.size
    px = img.load()
    # Seeded from the outer 40px frame, which is backdrop in both renders apart from the copyright
    # line - that line is an outlier the refits below drop.
    seed = [(x, y, px[x, y])
            for y in range(0, h, 3) for x in range(0, w, 3)
            if x < 40 or y < 40 or x >= w - 40 or y >= h - 40]
    coeffs = fit(seed, w, h)
    for _ in range(3):
        mp = render(coeffs, w, h).load()
        kept = [(x, y, px[x, y])
                for y in range(0, h, 3) for x in range(0, w, 3)
                if max(abs(px[x, y][c] - mp[x, y][c]) for c in range(3)) <= T0]
        if len(kept) < 400:
            break
        coeffs = fit(kept, w, h)
    return render(coeffs, w, h)


def reconstruct(seeds, mask):
    """Geodesic dilation - grows every surviving core back to its full component, nothing else."""
    grown = seeds
    for _ in range(80):
        nxt = ImageChops.multiply(grown.filter(ImageFilter.MaxFilter(3)), mask)
        if ImageChops.difference(nxt, grown).getbbox() is None:
            return nxt
        grown = nxt
    return grown


def key(path):
    """Return the render as RGBA with the studio backdrop removed."""
    img = Image.open(path).convert("RGB")
    w, h = img.size
    backdrop = backdrop_model(img)
    d = ImageChops.difference(img, backdrop).split()
    dist = ImageChops.lighter(ImageChops.lighter(d[0], d[1]), d[2])

    # Everything the model explains is a backdrop candidate; the flood decides which candidates are
    # actually backdrop, leaving the enclosed dark regions to be judged on their own.
    candidate = dist.point(lambda v: 255 if v <= T0 else 0)
    flooded = candidate.copy()
    for seed in ((0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)):
        ImageDraw.floodfill(flooded, seed, 128, thresh=0)
    outside = flooded.point(lambda v: 255 if v == 128 else 0)
    holes = ImageChops.subtract(candidate, outside)

    cores = holes.filter(ImageFilter.MinFilter(2 * COUNTER_RADIUS + 1))
    counters = reconstruct(cores, holes) if cores.getbbox() else Image.new("L", (w, h), 0)
    opaque = ImageChops.invert(ImageChops.lighter(outside, counters))

    # JPEG noise in the bright part of the vignette clears the threshold as single pixels. Anything
    # that does not survive a 3x3 erosion and is not connected to something that does is noise.
    opaque = reconstruct(opaque.filter(ImageFilter.MinFilter(3)), opaque)
    transparent = ImageChops.invert(opaque)

    # The ramp applies only in the band where the two regions meet, so compression mush inside the
    # mark cannot eat into it and the artwork's own black seams stay solid.
    ramp = dist.point(lambda v: 0 if v <= T0 else (255 if v >= T1 else int(255 * (v - T0) / (T1 - T0))))
    band = ImageChops.multiply(transparent.filter(ImageFilter.MaxFilter(5)),
                               opaque.filter(ImageFilter.MaxFilter(5)))
    alpha = ImageChops.lighter(ImageChops.multiply(opaque, ImageChops.invert(band)),
                               ImageChops.multiply(ramp, band))

    # Partial alpha belongs to the mark's own edge and nowhere else. Left alone, the haze the
    # vignette leaves across the bright half of image 2 is invisible but not empty, and every crop
    # taken from the alpha bounding box came out twice as wide as the artwork in it.
    near_solid = alpha.point(lambda v: 255 if v >= 200 else 0).filter(ImageFilter.MaxFilter(7))
    alpha = ImageChops.multiply(alpha, near_solid)

    # Unmix the backdrop out of the partly transparent edge pixels: without this the mark carries a
    # dark fringe everywhere it is composited on something lighter than the studio it was shot on.
    src, bg, ap = img.load(), backdrop.load(), alpha.load()
    out = Image.new("RGBA", (w, h))
    op = out.load()
    for y in range(h):
        for x in range(w):
            a = ap[x, y]
            if a == 0:
                op[x, y] = (0, 0, 0, 0)
            elif a == 255:
                op[x, y] = src[x, y] + (255,)
            else:
                s, b, f = src[x, y], bg[x, y], a / 255.0
                op[x, y] = tuple(
                    max(0, min(255, int(round((s[i] - b[i] * (1.0 - f)) / f)))) for i in range(3)
                ) + (a,)
    return out


# ------------------------------------------------------------------------------------------------
# Cuts and canvases.
# ------------------------------------------------------------------------------------------------
def cut(rgba, top, bottom, pad=6):
    """Trim to the marks between two scanlines - the copyright strip is never one of them."""
    strip = rgba.crop((0, top, rgba.width, bottom))
    # Measured on solid pixels, then padded back out: an edge ramp must not define the edge.
    box = strip.getchannel("A").point(lambda v: 255 if v >= 128 else 0).getbbox()
    if box is None:
        raise RuntimeError(f"no artwork between rows {top} and {bottom}")
    left, up, right, down = box
    return strip.crop((max(0, left - pad), max(0, up - pad),
                       min(strip.width, right + pad), min(strip.height, down + pad)))


def on_glass(art, radius=9, opacity=0.62, passes=2):
    """The same mark with a soft dark shadow under it, for drawing on a transparent window.

    The splash has no plate any more, so the white half of the wordmark was invisible against a
    light desktop - it is white artwork on whatever the operator happens to have behind it. A blur
    of the mark's own alpha, laid down in near-black beneath it, gives the white letters an edge on
    a white background without putting a rectangle back. Padding is part of the asset: a shadow
    cropped at the bbox is a shadow with a straight edge.
    """
    pad = radius * 3
    canvas = Image.new("RGBA", (art.width + (2 * pad), art.height + (2 * pad)), (0, 0, 0, 0))

    shadow = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    shadow.paste(Image.new("RGBA", art.size, (2, 5, 12, 255)), (pad, pad), art.getchannel("A"))
    shadow.putalpha(shadow.getchannel("A")
                    .filter(ImageFilter.GaussianBlur(radius))
                    .point(lambda v: min(255, int(v * opacity))))

    for _ in range(passes):                 # stacked rather than deepened: keeps the falloff soft
        canvas.alpha_composite(shadow)
    canvas.paste(art, (pad, pad), art)
    return canvas


def centred(art, size, fill=0.94):
    """Fit art into a transparent canvas, longest side to `fill` of it, centred."""
    cw, ch = size
    scale = min(cw * fill / art.width, ch * fill / art.height)
    scaled = art.resize((max(1, round(art.width * scale)), max(1, round(art.height * scale))),
                        Image.LANCZOS)
    canvas = Image.new("RGBA", size, (0, 0, 0, 0))
    canvas.paste(scaled, ((cw - scaled.width) // 2, (ch - scaled.height) // 2), scaled)
    return canvas


def write_icon(emblem, path):
    """A .ico Windows can use at every size it asks for - taskbar, alt-tab, Explorer, shortcut."""
    master = centred(emblem, (256, 256), fill=0.98)
    frames = []
    for size in ICON_SIZES:
        frame = master.resize((size, size), Image.LANCZOS)
        if size <= 48:
            # Facet seams are sub-pixel below 48px and LANCZOS turns them to haze; a light sharpen
            # keeps the silhouette readable at taskbar size instead of a blue smudge.
            frame = frame.filter(ImageFilter.UnsharpMask(radius=0.7, percent=90, threshold=0))
        frames.append(frame)
    frames[-1].save(path, format="ICO", sizes=[(s, s) for s in ICON_SIZES],
                    append_images=frames[:-1])


def save(img, name):
    path = ASSETS / name
    img.save(path, optimize=True)
    print(f"  {name:<32} {img.width}x{img.height}  {path.stat().st_size / 1024:6.1f} KB")


def main():
    ASSETS.mkdir(parents=True, exist_ok=True)

    print("keying SPLAT-primary.jpg ...")
    primary = key(BRAND / "SPLAT-primary.jpg")
    # Row bands measured off the alpha channel: crystal 125-470, SPLAT 500-603, strapline 623-645,
    # copyright 729-740. The copyright strip is cut everywhere - the app draws its own.
    p_emblem = cut(primary, 118, 478)
    p_lockup = cut(primary, 118, 652)
    save(p_emblem, "splat-emblem.png")
    save(p_lockup, "splat-lockup.png")
    # The splash window is transparent, so its copies carry their own shadow. Kept as separate
    # assets: the title-bar chip and the icons sit on solid surfaces and want the clean mark.
    save(on_glass(p_lockup, opacity=0.68, passes=3), "splat-lockup-onglass.png")

    print("keying SPLAT-enterprise.jpg ...")
    enterprise = key(BRAND / "SPLAT-enterprise.jpg")
    # Bands here: hexagon 134-458, SPLAT 478-567, strapline 581-606, copyright 660-676.
    e_emblem = cut(enterprise, 126, 466)
    save(e_emblem, "splat-enterprise-emblem.png")
    save(on_glass(e_emblem, radius=6), "splat-enterprise-emblem-onglass.png")
    save(cut(enterprise, 126, 614), "splat-enterprise-lockup.png")

    print("icons ...")
    write_icon(p_emblem, ASSETS / "splat.ico")
    print(f"  {'splat.ico':<32} {','.join(str(s) for s in ICON_SIZES)}")
    write_icon(e_emblem, ASSETS / "splat-enterprise.ico")
    print(f"  {'splat-enterprise.ico':<32} {','.join(str(s) for s in ICON_SIZES)}")

    # MSIX tiles. Package.appxmanifest has named these four files since the manifest was written and
    # none of them existed, so makeappx packed a package whose tiles were blank.
    print("MSIX tiles ...")
    save(centred(p_emblem, (44, 44)), "Square44x44Logo.png")
    save(centred(p_emblem, (150, 150)), "Square150x150Logo.png")
    save(centred(p_emblem, (50, 50)), "StoreLogo.png")
    save(centred(cut(primary, 118, 652), (310, 150), fill=0.86), "Wide310x150Logo.png")


if __name__ == "__main__":
    main()
